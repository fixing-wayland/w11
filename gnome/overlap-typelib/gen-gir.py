def load_table(path=TABLE_PATH):
    """The generations, oldest first.  A record missing a field is an error
    naming the field: half a record is how a description gets shipped under the
    wrong name."""
    with open(path, encoding="utf-8") as fh:
        table = json.load(fh)
    records = sorted(table.get("generations") or [], key=lambda g: g["shell_major"])
    if not records:
        raise SystemExit("gen-gir: %s names no generations" % path)
    for g in records:
        for f in TABLE_FIELDS:
            if g.get(f) is None:
                raise SystemExit("gen-gir: %s: the GNOME %s record has no %s"
                                 % (path, g.get("shell_major"), f))
    return records

