#!/usr/bin/env python3
"""Generate (and compile) the type descriptions the overlap extension ships.

libmutter is built with hidden visibility, but the test-export macro expands to a real
export, so the four symbols the extension needs are ordinary dynamic symbols in the
shipped library -- absent from the introspection data, not from the library.  A GNOME
Shell extension can prepend its own search path and load a type description it ships
itself, which is what these files are.

Two properties of what is emitted here matter more than anything else in this tree:

**No pointer is ever declared as a pointer.**  Every pointer field in Mutter's private
structures is declared `guint64`, so reading one yields a *number* and gjs never
dereferences anything on our behalf.  Stepping from one struct to the next goes through
`g_memdup2(ptr, n)` -- a bounded copy of exactly n bytes -- and `g_strndup(ptr, n)` for
the connector strings, which lets the extension range-check the number against
`/proc/self/maps` before any address is read at all.  A wrong offset then produces
garbage or a refusal, not a SIGSEGV; with pointers declared as pointers it produced a
dead gnome-shell (measured, GNOME 50.1, docs/Technical.md section 6).

**Nothing that can write ~/.config/monitors.xml is declared.**
`meta_monitor_config_manager_save_current()` is not in the file, and neither is any
other `*save*` symbol, so no code in the extension can reach the writer even by
mistake.  `tests/test_gnome_overlap.py` asserts that about the shipped .gir and about
the shipped .typelib bytes.

The layout below is measured, not assumed (docs/Technical.md section 6): `parent_config`
and `switch_config` were proved with sentinels written through the exported accessors.
`logical_monitor_configs` is at offset 40 on both mutter 14 and mutter 18; the tail and
the total size are not the same, which is exactly why there is one description per
generation and why the extension refuses to run one against the other.

    offset  mutter 14 (GNOME 46)      mutter 18 (GNOME 50)
    0..23   GObject                   GObject
    24      parent_config             parent_config
    32      key                       key
    40      logical_monitor_configs   logical_monitor_configs
    48      disabled_monitor_specs    disabled_monitor_specs
    56      flags                     (unused)
    60      layout_mode               (unused)
    64      switch_config             (unused)
    68      padding                   layout_mode
    72      --                        switch_config
    76      --                        padding
    size    72                        80

Usage:  python3 gnome/overlap-typelib/gen-gir.py [OUTDIR]
        (OUTDIR defaults to gnome/w11-overlap@w11/typelib)
        python3 gnome/overlap-typelib/gen-gir.py --check
        python3 gnome/overlap-typelib/gen-gir.py --from-header PATH [--shell N]

What it generates it generates *from the table*,
gnome/w11-overlap@w11/generations.json: one .gir and one
.typelib per record, and metadata.json's `shell-version` list.  So adding a
GNOME release is a record in that file (and its twin, GENERATIONS in
hacks/display/gnome_overlap.py) plus one run of this script -- there is no fourth
place to forget.

Needs `g-ir-compiler` (Ubuntu: libgirepository1.0-dev).  The compiled typelibs are
checked in because no desktop has that package installed; `--check` recompiles and
compares, which is how CI notices a .gir edited without a rebuild.  Its exit status
has three values, because "nothing disagreed" and "nothing was compared" are not the
same answer: 0 every namespace compared and agreed, 1 something is stale, 2 the
comparison could not be made here (no GIRepository to read a typelib with).  A CI
that treats 2 as a pass is a CI that ships whatever the .gir happened to say.

`--from-header` is the answer to a `typelib` or `sentinel` refusal after a GNOME
upgrade, and the only route by which a new generation should ever be added.  It reads
mutter's own `src/backends/meta-monitor-config-manager.h` -- the release's source, not
the running compositor -- lays `struct _MetaMonitorsConfig` out under the x86-64 rules
and prints the offsets, the instance size and the two numbers a record needs.  With
`--shell N` it compares those against the record shipped for GNOME N and says whether
they agree -- or, when there is no such record, prints the record to add and the two
files to add it to.

**It derives from source and never from a live libmutter, and that is the whole
point.**  A description generated by asking the compositor about itself would agree
with the compositor by construction: `struct-size` would pass because it was told the
size, and `sentinel` could only be satisfied by searching offsets until the marker
turned up, which is a search that confirms itself.  The independence of the shipped
description from the build it is checked against is what makes those two checks mean
anything -- it is why a wrong-generation description was caught before a byte was read
(measured on 24.04 and 26.04) -- and self-derivation would spend it to save a human
one afternoon per GNOME release.  So: derive the numbers here, from the release's
header, then prove them on a three-head VM as docs/Technical.md section 6 describes,
and only then add the generation to the four allowlists.
"""

